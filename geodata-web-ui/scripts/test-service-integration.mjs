import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { build, transform } from 'esbuild'

const root = fileURLToPath(new URL('..', import.meta.url))
const bundled = await build({ stdin: { contents: "export * from './src/features/datasets/serviceIntegration.ts'; export * from './src/features/datasets/service-url.ts';", resolveDir: root }, bundle: true, write: false, format: 'esm', platform: 'node', target: 'es2020' })
const { buildServiceIntegration: integration, shellQuote, jsString, extractSvcUrl } = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString('base64')}`)
const base = 'https://console.example.test/#/manage'
const samples = []
const wmsUrl = 'https://geo.example.test/geoserver/sdms/wms?service=WMS&version=1.1.0&request=GetMap&LAYERS=sdms%3Aroad&bbox=113,29,114,30&srs=EPSG%3A4326&styles=&width=768&height=670&format=image%2Fpng&token=demo-token&CQL_FILTER=name%3D%27a%27'
const wms = integration({ type: 'WMS', url: wmsUrl }, base)
samples.push(wms)
assert.equal(wms.sourceUrl, wmsUrl)
assert.equal(wms.layer, 'sdms:road')
assert.deepEqual(wms.examples.map((item) => item.id), ['curl', 'openlayers'])
const wmsCode = wms.examples[1].code
const wmsEndpoint = new URL(JSON.parse(wmsCode.match(/url: ("(?:\\.|[^"\\])*")/)[1]))
assert.equal(wmsEndpoint.pathname, '/geoserver/sdms/wms')
assert.equal(wmsEndpoint.searchParams.get('token'), 'demo-token')
assert.equal(wmsEndpoint.searchParams.get('CQL_FILTER'), "name='a'")
assert.equal(wmsEndpoint.searchParams.has('bbox'), false, 'viewport snapshots must not remain in the WMS endpoint')
assert.match(wmsCode, /LAYERS: "sdms:road"/)
assert.match(wmsCode, /VERSION: "1\.1\.0"/)
assert.ok(!wmsCode.includes('EPSG:3857'), 'client view projection must not be invented')
const wmtsUrl = 'https://geo.example.test/geoserver/gwc/service/wmts?token=keep&service=WMTS&version=1.1.0&request=GetTile&layer=sdms%3Adom&tileMatrixSet=EPSG%3A4326&tileMatrix=EPSG%3A4326%3A7&tileRow=9&tileCol=12&format=image%2Fpng'
const wmts = integration({ type: 'WMTS', url: wmtsUrl }, base)
samples.push(wmts)
const capabilities = new URL(wmts.capabilitiesUrl)
assert.equal(capabilities.origin, new URL(wmtsUrl).origin)
assert.equal(capabilities.pathname, new URL(wmtsUrl).pathname)
assert.equal(capabilities.searchParams.get('token'), 'keep')
assert.equal(capabilities.searchParams.get('REQUEST'), 'GetCapabilities')
assert.equal(capabilities.searchParams.get('VERSION'), '1.0.0')
assert.ok(![...capabilities.searchParams.keys()].some((key) => /^(tilematrix|tilerow|tilecol|layer|format)$/i.test(key)))
assert.match(wmts.examples[1].code, /optionsFromCapabilities/)
assert.match(wmts.examples[1].code, /matrixSet: "EPSG:4326"/)
assert.ok(!wmts.examples[1].code.includes('EPSG:4326:7'), 'sample level must not be used as the full tile grid')
const mvtUrl = wmtsUrl.replace('image%2Fpng', 'application%2Fvnd.mapbox-vector-tile')
const mvt = integration({ type: 'MVT', url: mvtUrl }, base)
samples.push(mvt)
assert.match(mvt.examples[1].code, /new VectorTileSource/)
assert.match(mvt.examples[1].code, /tileGrid: options.tileGrid/)
assert.match(mvt.examples[1].code, /tileUrlFunction: wmtsSource.getTileUrlFunction\(\)/)
assert.ok(!mvt.examples[1].code.includes('createXYZ'), 'MVT matrix origin, sizes and resolutions must come from capabilities')
assert.equal(extractSvcUrl({ list: [{ '关键字': 'WMTS', '服务路径': mvtUrl }] }, 'MVT'), mvtUrl, 'legacy WMTS keyword must not hide proven MVT URLs')
assert.equal(extractSvcUrl({ list: [{ '关键字': 'WMTS', '服务路径': wmtsUrl }] }, 'MVT'), '', 'raster WMTS must never be inferred as MVT')
assert.equal(extractSvcUrl({ list: [{ '关键字': 'WMTS', '服务路径': wmtsUrl + '&note=application/vnd.mapbox-vector-tile' }] }, 'MVT'), '')
const missingLayer = integration({ type: 'WMTS', url: 'https://geo.example.test/wmts?service=WMTS' })
assert.deepEqual(missingLayer.examples.map((item) => item.id), ['curl'])
assert.match(missingLayer.note, /缺少 layer/)
const wrongFormat = integration({ type: 'MVT', url: wmtsUrl })
assert.equal(wrongFormat.examples.length, 1)
assert.match(wrongFormat.note, /未声明可确认的 MVT/)

const wfs = integration({ type: 'WFS', url: 'https://geo.example.test/geoserver/sdms/wfs?service=WFS&version=1.1.0&request=GetFeature&typeNames=sdms%3Aroad&BBOX=113,29,114,30&CQL_FILTER=height%3E3&MAXFEATURES=9000&token=keep' })
samples.push(wfs)
const feature = new URL(wfs.requestUrl)
assert.equal(feature.searchParams.get('typeName'), 'sdms:road')
assert.equal(feature.searchParams.get('maxFeatures'), '1000')
assert.equal(feature.searchParams.get('outputFormat'), 'application/json')
assert.equal(feature.searchParams.get('BBOX'), '113,29,114,30')
assert.equal(feature.searchParams.get('CQL_FILTER'), 'height>3')
assert.equal(feature.searchParams.get('token'), 'keep')
assert.deepEqual(wfs.examples.map((item) => item.id), ['curl', 'geojson'])
const wfs2 = integration({ type: 'WFS', url: 'https://geo.example.test/wfs?service=WFS&version=2.0.0&request=GetFeature&typeNames=actual%3Aplot&count=35' })
assert.equal(new URL(wfs2.requestUrl).searchParams.get('count'), '35')
assert.equal(new URL(wfs2.requestUrl).searchParams.has('maxFeatures'), false)
const mapOnFeatureEndpoint = integration({ type: 'WFS', url: 'https://geo.example.test/wfs?version=1.1.0&request=GetMap&layers=actual%3Aplot&srs=EPSG%3A4326&format=image%2Fpng&width=700&height=300' })
assert.equal(new URL(mapOnFeatureEndpoint.requestUrl).pathname, '/wfs')
assert.equal(new URL(mapOnFeatureEndpoint.requestUrl).searchParams.get('typeName'), 'actual:plot')
assert.equal(new URL(mapOnFeatureEndpoint.requestUrl).searchParams.get('srsName'), 'EPSG:4326')
assert.equal(new URL(mapOnFeatureEndpoint.requestUrl).searchParams.has('width'), false)
const wrongEndpoint = integration({ type: 'WFS', url: wmsUrl })
assert.equal(wrongEndpoint.examples.length, 0, 'a WMS URL cannot silently become an invented WFS endpoint')
const noVersion = integration({ type: 'WFS', url: 'https://geo.example.test/wfs?typeNames=actual%3Aplot' })
assert.equal(noVersion.examples.length, 0, 'missing version must not result in an unbounded feature request')

const tileset = integration({ type: '3DTiles', url: '/published/actual/tileset.json?signature=demo#scene' }, base)
samples.push(tileset)
assert.equal(tileset.sourceUrl, 'https://console.example.test/published/actual/tileset.json?signature=demo#scene')
assert.ok(!tileset.requestUrl.includes('#'))
assert.match(tileset.examples[1].code, /Cesium3DTileset/)
assert.match(tileset.examples[1].requirement, /安装 cesium/)
assert.match(tileset.examples[1].code, /viewer.destroy\(\)/)
assert.equal(integration({ type: '3DTiles', url: 'https://geo.example.test/model.glb' }).examples.length, 1, 'unpositioned glTF must not receive invented coordinates')
for (const url of ['', 'javascript:alert(1)', 'data:text/html,unsafe', 'file:///etc/hosts']) {
  assert.equal(integration({ type: 'WMS', url }, base).sourceUrl, '')
}
const adversarial = "apostrophe' double\" dollar$(printf injected) backtick`printf injected` backslash\\ line\nbreak </script>\u2028\u2029"
assert.equal(execFileSync('/bin/sh', ['-c', `printf '%s' ${shellQuote(adversarial)}`], { encoding: 'utf8' }), adversarial)
assert.equal(JSON.parse(jsString(adversarial)), adversarial)
assert.ok(!jsString(adversarial).includes('</script>'))
assert.ok(!jsString(adversarial).includes('\u2028'))
for (const packet of samples) for (const example of packet.examples) {
  if (example.id === 'curl') execFileSync('/bin/sh', ['-n'], { input: example.code })
  else await transform(example.code, { loader: 'js', target: 'es2020' })
}
console.log('Service integration: real URL extraction, bounded WFS, capabilities-driven grids, protocol selection and shell/JS escaping passed.')
