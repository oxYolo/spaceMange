import assert from 'node:assert/strict'
import { build } from 'esbuild'
const bundle = await build({ entryPoints: ['src/features/datasets/uploadValidation.ts'], bundle: true, write: false, format: 'esm', platform: 'node' })
const { validateDatasetFiles: validate, acceptedDatasetFiles, inspectShapeFiles, datasetFormatHint } = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`)
const file = (name, size = 100) => ({ name, size })
const shape = [file('roads.SHP'), file('roads.shx'), file('roads.dbf')]
assert.equal(validate('vector', shape), '')
assert.match(validate('vector', shape.slice(0, 2)), /不完整/)
assert.match(validate('vector', [...shape, file('other.prj')]), /相同/)
assert.match(validate('vector', [...shape, file('roads.SHP')]), /不能重复/)
assert.match(validate('raster', [file('image.pdf')]), /不支持/)
assert.match(validate('raster', [file('image.tif', 0)]), /空文件/)
assert.equal(validate('terrain', [file('dem.tiff')]), '')
assert.equal(validate('oblique', [file('city.zip')]), '')
assert.match(validate('oblique', [file('city.las')]), /不支持/)
assert.match(validate('', [file('city.zip')], true), /请选择数据类型/)
assert.match(validate('raster', [file('image.tif')], true), /仅三维/)
assert.equal(validate('oblique', [file('city.zip')], true), '')
assert.match(validate('raster', [file('a.tif'), file('b.tif')]), /一个文件/)
assert.equal(acceptedDatasetFiles('vector'), '.shp,.shx,.dbf,.prj,.cpg')
assert.deepEqual(inspectShapeFiles([file('roads.shp')]).missing, ['.shx', '.dbf'])
assert.deepEqual(inspectShapeFiles(shape).missing, [])
assert.deepEqual(inspectShapeFiles(shape).optionalMissing, ['.prj', '.cpg'])
assert.match(datasetFormatHint('pointcloud'), /\.las、\.laz/)
assert.doesNotMatch(datasetFormatHint('pointcloud'), /\.shp|\.ifc/)
assert.match(datasetFormatHint('tileset'), /完成后直接发布/)
console.log('上传校验通过：完整文件组、匹配类型、空文件及重复文件检查')
